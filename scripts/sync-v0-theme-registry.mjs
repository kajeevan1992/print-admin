import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const themesRoot = path.join(root, 'src/v0-themes');
const generatedRegistryPath = path.join(root, 'src/theme-runtime/built-in/v0-installed.generated.ts');
const generatedCatalogPath = path.join(themesRoot, 'installed-themes.generated.json');
const checkOnly = process.argv.includes('--check');

function clean(value) {
  return String(value || '').trim();
}

function identifier(value) {
  const words = clean(value).split(/[^a-zA-Z0-9]+/).filter(Boolean);
  const output = words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('');
  return output && /^[A-Za-z]/.test(output) ? output : `Theme${output || 'Package'}`;
}

function variable(value) {
  const output = identifier(value);
  return output.charAt(0).toLowerCase() + output.slice(1);
}

function manifestValue(content, field) {
  const match = content.match(new RegExp(`^\\s*${field}\\s*:\\s*['\"\\x60]([^'\"\\x60]+)['\"\\x60]\\s*,?`, 'm'));
  return clean(match?.[1]);
}

function assertIndexExports(folder, content) {
  for (const name of ['ThemeHomePage', 'themeManifest', 'themeRouteViews']) {
    if (!new RegExp(`\\b${name}\\b`).test(content)) throw new Error(`src/v0-themes/${folder}/index.ts must export ${name}.`);
  }
}

function readPackages() {
  if (!fs.existsSync(themesRoot)) throw new Error('src/v0-themes is missing.');
  const folders = fs.readdirSync(themesRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('_') && !entry.name.startsWith('.'))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const packages = folders.map((folder) => {
    const directory = path.join(themesRoot, folder);
    const manifestPath = path.join(directory, 'manifest.ts');
    const indexPath = path.join(directory, 'index.ts');
    if (!fs.existsSync(manifestPath)) throw new Error(`src/v0-themes/${folder} is missing manifest.ts.`);
    if (!fs.existsSync(indexPath)) throw new Error(`src/v0-themes/${folder} is missing index.ts.`);
    const content = fs.readFileSync(manifestPath, 'utf8');
    assertIndexExports(folder, fs.readFileSync(indexPath, 'utf8'));
    const key = manifestValue(content, 'key');
    const name = manifestValue(content, 'name');
    const version = manifestValue(content, 'version');
    if (!key || !name || !version) throw new Error(`src/v0-themes/${folder}/manifest.ts must declare key, name and version as string literals.`);
    if (key !== `${folder}-native`) throw new Error(`Theme folder ${folder} must use manifest key ${folder}-native, found ${key}.`);
    if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) throw new Error(`Theme ${key} has invalid semantic version ${version}.`);
    return {
      folder,
      key,
      name,
      version,
      identifier: identifier(folder),
      variable: variable(folder),
    };
  });

  const keys = new Set();
  for (const item of packages) {
    if (keys.has(item.key)) throw new Error(`Duplicate installed theme key: ${item.key}.`);
    keys.add(item.key);
  }
  return packages;
}

function registrySource(packages) {
  const imports = packages.map((item) => `import {\n  ThemeHomePage as ${item.identifier}ThemeHomePage,\n  themeManifest as ${item.variable}ThemeManifest,\n  themeRouteViews as ${item.variable}ThemeRouteViews,\n} from '@/v0-themes/${item.folder}';`).join('\n');
  const definitions = packages.map((item) => `  createV0ThemeDefinition({\n    manifest: ${item.variable}ThemeManifest,\n    HomePage: ${item.identifier}ThemeHomePage,\n    routeViews: ${item.variable}ThemeRouteViews,\n    themeStyle: '${item.folder}',\n  }),`).join('\n');
  return `/* This file is generated by scripts/sync-v0-theme-registry.mjs. Do not edit manually. */\nimport { createV0ThemeDefinition } from '@/theme-runtime/v0-package-adapter';\n${imports ? `${imports}\n` : ''}\nexport const INSTALLED_V0_THEME_DEFINITIONS = [\n${definitions}\n];\n`;
}

function catalogSource(packages) {
  return `${JSON.stringify({
    schemaVersion: 1,
    themes: packages.map(({ folder, key, name, version }) => ({ folder, key, name, version })),
  }, null, 2)}\n`;
}

function writeOrCheck(file, expected) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (current === expected) return false;
  if (checkOnly) throw new Error(`${path.relative(root, file).replaceAll('\\', '/')} is stale. Run pnpm theme:registry.`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, expected);
  return true;
}

try {
  const packages = readPackages();
  const changed = [
    writeOrCheck(generatedRegistryPath, registrySource(packages)),
    writeOrCheck(generatedCatalogPath, catalogSource(packages)),
  ].some(Boolean);
  if (checkOnly) console.log(`V0 theme registry is current (${packages.length} installed theme${packages.length === 1 ? '' : 's'}).`);
  else console.log(changed ? `Updated V0 theme registry for ${packages.length} installed theme${packages.length === 1 ? '' : 's'}.` : 'V0 theme registry already current.');
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
